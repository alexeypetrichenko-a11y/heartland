#!/usr/bin/env python3
"""
WORLD-03: render the package's machine-readable results as one Markdown report (REPORT.md in the package).

  python3 scenarios/pipeline/report.py scenarios/europe-2023/<version>

Reads calibration-report.json, provenance.json, manifest.json, validation-report.json and (when present)
benchmark-node.json and benchmark-browser.json from the package directory. Nothing is computed that is not
in those files, apart from formatting and simple sums.
"""
import json, os, sys

def load(d, name):
    p = os.path.join(d, name)
    return json.load(open(p, encoding='utf-8')) if os.path.exists(p) else None

def pct(x, digits=1):
    return f'{x * 100:.{digits}f}%'

def main(d):
    cal, prov, man = load(d, 'calibration-report.json'), load(d, 'provenance.json'), load(d, 'manifest.json')
    val, bn, bb = load(d, 'validation-report.json'), load(d, 'benchmark-node.json'), load(d, 'benchmark-browser.json')
    zones = {z['id']: z for z in prov['zones']}
    L = []
    w = L.append
    w(f'# Scenario {man["id"]} {man["version"]}: calibration, validation and performance report')
    w('')
    w('Generated by `scenarios/pipeline/report.py` from the JSON files in this directory. **Review draft: not connected to the game.**')
    w('')
    w('| | |')
    w('|---|---|')
    w(f'| Status | {man["status"]} |')
    w(f'| World fingerprint | `{man["worldFingerprint"]}` |')
    w(f'| Week-1 economy hash | `{man["week1EconomyHash"]}` |')
    w(f'| Content fingerprint | `{man["contentFingerprint"]}` |')
    w(f'| Calibration | {cal["targetsMissed"]} targets missed; {len(cal["rounds"])} rounds of the unchanged engine |')
    if val:
        s = val['summary']
        w(f'| Validation | {s["pass"]} pass, {s["warn"]} warning, {s["fail"]} fail |')
    w('')
    # Validation
    if val:
        w('## 1. Validation')
        w('')
        w('| Check | Result | Detail |')
        w('|---|---|---|')
        for r in val['results']:
            w(f'| {r["check"]} | **{r["result"].upper()}** | {r["detail"].replace("|", "/")} |')
        w('')
    # Calibration: countries
    w('## 2. Calibration')
    w('')
    w('### 2.1 Real output shares (target ±3% relative)')
    w('')
    w('Country share of the scenario\'s real output: data (2023 GDP at PPP) vs the engine\'s week 1.')
    w('')
    w('| Country | Target share | Engine share | Relative error |')
    w('|---|---:|---:|---:|')
    for c in sorted(cal['countries'], key=lambda c: -c['targetShare']):
        w(f'| {c["id"]} | {pct(c["targetShare"], 2)} | {pct(c["achievedShare"], 2)} | {c["relativeError"] * 100:+.2f}% |')
    w('')
    worst = sorted(cal['zones'], key=lambda z: -abs(z['relativeError']))
    w(f'All 61 zones: worst relative error {worst[0]["relativeError"] * 100:+.2f}% ({worst[0]["id"]}). Per zone (technology is the fitted input):')
    w('')
    w('| Zone | Kind | Population (M) | Target output (intl $ bn) | Target share | Engine share | Error | Technology |')
    w('|---|---|---:|---:|---:|---:|---:|---:|')
    for z in cal['zones']:
        p = zones[z['id']]
        w(f'| {z["id"]} | {z["kind"]} | {p["population"]["value"]:,.2f} | {p["output_target"]["value"]:,.1f} | {pct(z["targetShare"], 3)} | {pct(z["achievedShare"], 3)} | {z["relativeError"] * 100:+.2f}% | {z["technology"]:.3f} |')
    w('')
    # Fiscal
    w('### 2.2 Taxes, spending and debt (target ±1 percentage point)')
    w('')
    w('Ratios to GDP. "Input" is the engine rate or share after fitting; "engine" is week 1. Blocs and missing values use engine defaults (no target).')
    w('')
    fields = ['taxIncome', 'taxConsumption', 'taxCorporate', 'spendAdministration', 'spendSocial', 'spendMilitary', 'spendInfrastructure', 'debtToGdp']
    w('| Country | ' + ' | '.join(fields) + ' |')
    w('|---|' + '---|' * len(fields))
    for f in cal['fiscal']:
        rows = {r['field']: r for r in f['rows']}
        cells = []
        for k in fields:
            r = rows[k]
            if r['target'] is None:
                cells.append(f'— (default; engine {r["achieved"] * 100:.1f})')
            else:
                miss = abs(r['achieved'] - r['target']) > 0.01
                cell = f'{r["target"] * 100:.1f} → {r["achieved"] * 100:.1f}'
                cells.append(f'**{cell}** ✗' if miss else cell)
        w(f'| {f["id"]} | ' + ' | '.join(cells) + ' |')
    w('')
    w('Format: target → engine (% of GDP; debt in % of yearly GDP). ✗ = outside ±1 pp.')
    w('')
    # Groups
    w('### 2.3 Sector groups (informational: advantages are set from data, not fitted)')
    w('')
    w('Engine output share by group vs the data group share of GVA, averaged over zones (absolute percentage points).')
    w('')
    keys = ['food', 'energy', 'materials', 'industrial', 'consumer']
    w('| Group | Mean data share | Mean engine share | Mean absolute gap (pp) |')
    w('|---|---:|---:|---:|')
    for k in keys:
        dv = [g['data'][k] for g in cal['groups']]
        ev = [g['engine'][k] for g in cal['groups']]
        gap = sum(abs(a - b) for a, b in zip(dv, ev)) / len(dv)
        w(f'| {k} | {pct(sum(dv) / len(dv))} | {pct(sum(ev) / len(ev))} | {gap * 100:.1f} |')
    w('')
    w('The engine\'s group shares cover goods only; data shares are shares of all value added (services are the remainder), so the two are not on the same base. Reported for review, not as a target.')
    w('')
    # Military
    w('## 3. Military starting forces (draft)')
    w('')
    m = prov['military']
    w(f'Parameter: {m["parameter_personnel_equivalents_per_division"]["value"]:,} personnel equivalents per division ({m["parameter_personnel_equivalents_per_division"]["method"]}).')
    w('')
    w('| Country | Status | Personnel equivalents | Divisions |')
    w('|---|---|---:|---:|')
    for cid, v in m['countries'].items():
        w(f'| {cid} | {v["status"]} | {v.get("personnel_equivalents", "—") if v.get("personnel_equivalents") is None else f"{v["personnel_equivalents"]:,}"} | {v["divisions"] if v["divisions"] is not None else "unresolved"} |')
    unresolved = [f'{c}: {v["reason"]}' for c, v in m['countries'].items() if v['status'] == 'unresolved']
    for u in unresolved:
        w('')
        w(f'- {u}')
    w('')
    # Performance
    if bn:
        w('## 4. Performance on this scenario (measured)')
        w('')
        w(f'Node {bn["node"]} ({bn["platform"]}), {bn["zones"]} zones, {bn["lanes"]} lanes, {bn["repeats"]} runs of 155 weeks, player `{bn["player"]}`:')
        w('')
        w('| Measure | Value |')
        w('|---|---:|')
        w(f'| Week median / 95th pct / slowest | {bn["weekMs"]["median"]:.1f} / {bn["weekMs"]["p95"]:.1f} / {bn["weekMs"]["max"]:.0f} ms |')
        w(f'| Load week-1 save | {bn["loadMs"]:.0f} ms |')
        w(f'| Week-1 save | {bn["week1SaveKb"]:,.0f} KB ({bn["week1SaveGzipKb"]:,.0f} KB gzip) |')
        w(f'| Week-156 save | {bn["week156SaveKb"]:,.0f} KB ({bn["week156SaveGzipKb"]:,.0f} KB gzip); save {bn["saveMs"]:.0f} ms, restore {bn["restoreMs"]:.0f} ms; round trip identical: {bn["saveRoundTripIdentical"]} |')
        w(f'| Heap after 156 weeks | {bn["heapMb"]["after156Weeks"]:.0f} MB |')
        w('')
    if bb:
        w('Headless Chromium with CPU throttling (a proxy, not an iPhone):')
        w('')
        w('| Slowdown | Run | Start from save (ms) | Week median (ms) | 95th pct (ms) | Slowest (ms) | Save / restore (ms) | JS heap (MB) |')
        w('|---:|---:|---:|---:|---:|---:|---|---:|')
        for r in bb['results']:
            heap = '—' if r['heapMb'] is None else f'{r["heapMb"]:.0f}'
            w(f'| {r["cpuThrottle"]}× | {r.get("run", 1)} | {r["startFromSaveMs"]:.0f} | {r["weekMs"]["median"]:.0f} | {r["weekMs"]["p95"]:.0f} | {r["weekMs"]["max"]:.0f} | {r["saveMs"]:.0f} / {r["restoreMs"]:.0f} | {heap} |')
        w('')
    if bn:
        w('## 5. Behaviour after week 1 (the autopilot steers every country; the player issues no commands)')
        w('')
        w('| Country | Week | Debt / GDP | Market rate | Interest / GDP | Unemployment | Stability | Market access | Regime changes |')
        w('|---|---:|---:|---:|---:|---:|---:|---|---:|')
        for cid, weeks in bn['trajectory'].items():
            for week, v in weeks.items():
                w(f'| {cid} | {week} | {v["debtToGdp"]:.2f} | {pct(v["marketRate"])} | {pct(v["interestShareOfGdp"])} | {pct(v["unemployment"])} | {v["stability"]:.0f} | {"yes" if v["marketAccess"] else "**no**"} | {v["regime"]} |')
        w('')
    if bn and bn.get('events'):
        w('Crisis events in the first 155 weeks (week numbers):')
        w('')
        w('| Event | Countries and weeks |')
        w('|---|---|')
        for t, by in bn['events'].items():
            w(f'| {t} | ' + '; '.join(f'{c}: {", ".join(map(str, ws)) if len(ws) <= 8 else f"{len(ws)} times from week {ws[0]}"}' for c, ws in sorted(by.items())) + ' |')
        w('')
    # Issues
    w('## 6. Estimates, unavailable values, engine limits and licensing risks')
    w('')
    w('| Kind | Subject | Detail |')
    w('|---|---|---|')
    for i in prov['issues']:
        w(f'| {i["kind"]} | {i["subject"]} | {i["text"]} |')
    w('')
    w('## 7. Sources')
    w('')
    w('| Snapshot | Publisher dataset | Retrieved | Publisher update | Licence status |')
    w('|---|---|---|---|---|')
    for sid, s in prov['sources'].items():
        w(f'| `{sid}` | {s["publisher"]}: {s["dataset"]} | {s["retrieved"]} | {s["publisher_updated"] or "—"} | {s["licence_status"]} |')
    w('')
    with open(os.path.join(d, 'REPORT.md'), 'w', encoding='utf-8') as f:
        f.write('\n'.join(L) + '\n')
    print(f'wrote {os.path.join(d, "REPORT.md")} ({len(L)} lines)')

if __name__ == '__main__':
    main(sys.argv[1])
