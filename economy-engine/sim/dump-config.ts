import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_GOODS, DEFAULT_PARAMS } from '../src/index.ts';

/** Writes reports/CONFIG_REFERENCE.md: the goods table and every parameter with its default and its source comment. */
const here = dirname(fileURLToPath(import.meta.url));
const source = readFileSync(resolve(here, '..', 'src', 'config', 'defaults.ts'), 'utf8');
const block = source.slice(source.indexOf('export const DEFAULT_PARAMS'));
const lines = block.split('\n');
const sections: { title: string; rows: { key: string; value: string; note: string }[] }[] = [];
let note: string[] = [];
for (const line of lines) {
  const text = line.trim();
  const heading = text.match(/^\/\/ --- (.+?) -+$/);
  if (heading) { sections.push({ title: heading[1], rows: [] }); note = []; continue; }
  const single = text.match(/^\/\*\* (.+) \*\/$/);
  if (single) { note.push(single[1]); continue; }
  const entry = text.match(/^(\w+): (.+),$/);
  if (entry && sections.length > 0 && entry[1] in DEFAULT_PARAMS) {
    const value = (DEFAULT_PARAMS as unknown as Record<string, unknown>)[entry[1]];
    sections[sections.length - 1].rows.push({ key: entry[1], value: Array.isArray(value) ? `[${value.join(', ')}]` : String(value), note: note.join(' ') });
    note = [];
  }
}
const out: string[] = ['# Configuration reference', '', 'Generated by `npm run config-reference` from `src/config/defaults.ts`. **Every value is a provisional balancing choice for the fictional test worlds, not an approved game rule** (GAME_DESIGN.md section 17, item 1).', '', '## Goods and sectors', '',
  'Margins and labour needs are *derived* so that a sector running at its normal utilisation, at base price, earns exactly the reference return (10% + depreciation) on its capital.', '',
  '| Good | Tradable | Spoilage / week | Freight | Cover (weeks) | Inputs per unit | Labour / unit | Capital (weeks of output per unit capacity) | Depreciation / yr | Build (weeks) | Normal utilisation | Normal margin | Subsistence / person / week | Household budget share | Resource-based |', '|---|---|---:|---:|---:|---|---:|---:|---:|---:|---:|---:|---:|---:|---|'];
for (const g of DEFAULT_GOODS) {
  out.push(`| ${g.name} | ${g.tradable ? 'yes' : 'no (local)'} | ${g.spoilage} | ${g.freight} | ${g.coverWeeks} | ${g.inputs.map(i => `${i.amount} ${i.goodId}`).join(', ')} | ${g.laborPerUnit.toFixed(3)} | ${g.capitalWeeks} | ${g.depreciation} | ${g.constructionWeeks} | ${g.normalUtilization} | ${(g.targetMargin * 100).toFixed(1)}% | ${g.subsistence} | ${g.budgetShare} | ${g.resourceBased ? 'yes' : 'no'} |`);
}
out.push('', '### How each kind of spending is composed (share of the value spent on each good)', '', '| Good | Administration | Military | Infrastructure | Private investment |', '|---|---:|---:|---:|---:|');
for (const g of DEFAULT_GOODS) out.push(`| ${g.name} | ${g.administrationShare} | ${g.militaryShare} | ${g.infrastructureShare} | ${g.investmentShare} |`);
out.push('', '## Parameters', '');
for (const section of sections) {
  if (section.rows.length === 0) continue;
  out.push(`### ${section.title}`, '', '| Parameter | Default | Meaning |', '|---|---:|---|');
  for (const row of section.rows) out.push(`| \`${row.key}\` | ${row.value} | ${row.note} |`);
  out.push('');
}
mkdirSync(resolve(here, '..', 'reports'), { recursive: true });
writeFileSync(resolve(here, '..', 'reports', 'CONFIG_REFERENCE.md'), out.join('\n'));
console.log(`wrote ${out.length} lines`);
