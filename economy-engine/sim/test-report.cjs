/*
 * Runs every automated check and records the real output in reports/TEST_RESULTS.md.
 *   node sim/test-report.cjs
 */
const { spawnSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const game = path.resolve(root, '..');
const sections = [];
let failed = false;

function run(title, command, args, cwd, summarize) {
  const started = Date.now();
  const result = spawnSync(command, args, { cwd, encoding: 'utf8', maxBuffer: 256 * 1024 * 1024, shell: false });
  const output = `${result.stdout || ''}${result.stderr || ''}`;
  const ok = result.status === 0;
  if (!ok) failed = true;
  sections.push({ title, command: `${command} ${args.join(' ')}`, cwd: path.relative(game, cwd) || '.', ok, seconds: ((Date.now() - started) / 1000).toFixed(1), output, summary: summarize ? summarize(output) : '' });
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${title} (${((Date.now() - started) / 1000).toFixed(1)} s)`);
}
const tap = output => ['tests', 'pass', 'fail', 'skipped'].map(key => { const m = output.match(new RegExp(`^ℹ ${key} (\\d+)`, 'm')) || output.match(new RegExp(`^# ${key} (\\d+)`, 'm')); return m ? `${key} ${m[1]}` : ''; }).filter(Boolean).join(', ');

const node = process.execPath;
run('Engine type-check (strict, src+sim+tests+examples)', node, [path.join(game, 'node_modules', 'typescript', 'bin', 'tsc'), '-p', 'tsconfig.json'], root);
run('Engine type-check (core only: no Node or DOM types available)', node, [path.join(game, 'node_modules', 'typescript', 'bin', 'tsc'), '-p', 'tsconfig.core.json'], root);
run('Engine fast test suite', node, ['--experimental-strip-types', '--test', '--test-reporter=spec', ...fs.readdirSync(path.join(root, 'tests')).filter(f => f.endsWith('.test.ts')).map(f => `tests/${f}`)], root, tap);
run('Engine long test (10,000 consecutive weeks, save/restore at 5,000)', node, ['--experimental-strip-types', '--test', '--test-reporter=spec', 'tests/long/long.test.ts'], root, tap);
run('Existing game: npm test (unchanged tests)', 'npm', ['test'], game, tap);
run('Existing game: npm run build', 'npm', ['run', 'build'], game);

const env = [`Node ${process.version}`, `${process.platform} ${process.arch}`, `generated ${new Date().toISOString().slice(0, 10)}`].join(', ');
const lines = ['# Test results', '', `Generated by \`node sim/test-report.cjs\` (${env}). The output below is the verbatim output of each command.`, '',
  '| Check | Result | Time | Summary |', '|---|---|---:|---|', ...sections.map(s => `| ${s.title} | ${s.ok ? 'PASS' : '**FAIL**'} | ${s.seconds} s | ${s.summary} |`), ''];
for (const s of sections) {
  lines.push(`## ${s.title}`, '', `\`${s.command}\` (in \`${s.cwd}\`)`, '', '```text', s.output.trim().split('\n').slice(-400).join('\n'), '```', '');
}
fs.mkdirSync(path.join(root, 'reports'), { recursive: true });
fs.writeFileSync(path.join(root, 'reports', 'TEST_RESULTS.md'), lines.join('\n'));
console.log(failed ? 'SOME CHECKS FAILED' : 'ALL CHECKS PASSED');
process.exit(failed ? 1 : 0);
