import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ScenarioResult } from './scenarios.ts';
import { Context, SCENARIOS } from './scenarios.ts';

/**
 * Runs the ten mandatory scenarios and writes reports/SCENARIO_REPORTS.md and
 * reports/scenarios.json. Usage: npm run scenarios [-- 3 7]  (optional ids).
 */
const here = dirname(fileURLToPath(import.meta.url));
const outDir = resolve(here, '..', 'reports');
const wanted = process.argv.slice(2).map(Number).filter(Number.isInteger);

function markdown(results: ScenarioResult[]): string {
  const lines: string[] = [
    '# HEARTLAND economic engine - scenario reports',
    '',
    'Generated by `npm run scenarios`. Every scenario compares a run with an event against a control run from the same starting state, with every government on the same rule-based fiscal autopilot. Numbers below are measured output of those runs; nothing is copied by hand.',
    '',
    '| # | Scenario | Weeks | Checks passed |',
    '|---|---|---:|---:|',
    ...results.map(r => `| ${r.id} | ${r.title} | ${r.weeks} | ${r.checks.filter(c => c.pass).length}/${r.checks.length} |`),
    '',
  ];
  for (const r of results) {
    lines.push(`## ${r.id}. ${r.title}`, '', `**Setup.** ${r.setup}`, '', '**Measured indicators**', '', '| Indicator | Value | Note |', '|---|---|---|');
    for (const i of r.indicators) lines.push(`| ${i.label} | ${i.value}${i.unit ? ' ' + i.unit : ''} | ${i.note ?? ''} |`);
    lines.push('', `**${r.table.caption}**`, '', `| ${r.table.headers.join(' | ')} |`, `|${r.table.headers.map(() => '---').join('|')}|`);
    for (const row of r.table.rows) lines.push(`| ${row.join(' | ')} |`);
    lines.push('', '**Mechanisms observed**', '', ...r.mechanisms.map(m => `- ${m}`), '', '**Automated checks**', '', '| Check | Result | Detail |', '|---|---|---|');
    for (const c of r.checks) lines.push(`| ${c.name} | ${c.pass ? 'PASS' : '**FAIL**'} | ${c.detail} |`);
    lines.push('');
  }
  return lines.join('\n');
}

const context = new Context();
const results: ScenarioResult[] = [];
for (const scenario of SCENARIOS) {
  if (wanted.length > 0 && !wanted.includes(scenario.id)) continue;
  const result = scenario.run(context);
  results.push(result);
  const failed = result.checks.filter(c => !c.pass);
  console.log(`#${result.id} ${result.title}: ${result.checks.length - failed.length}/${result.checks.length} checks passed (${(result.runtimeMs / 1000).toFixed(1)} s)`);
  for (const c of failed) console.log(`    FAIL ${c.name}: ${c.detail}`);
  if (process.env.VERBOSE) for (const i of result.indicators) console.log(`    ${i.label}: ${i.value}${i.note ? '  (' + i.note + ')' : ''}`);
}
if (wanted.length === 0) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(resolve(outDir, 'SCENARIO_REPORTS.md'), markdown(results));
  writeFileSync(resolve(outDir, 'scenarios.json'), JSON.stringify(results, null, 2));
  console.log(`Reports written to ${outDir}`);
}
process.exitCode = results.some(r => r.checks.some(c => !c.pass)) ? 1 : 0;
