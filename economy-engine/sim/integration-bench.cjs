/*
 * Integration API benchmark (ECON-05): the game's fictional scenario (3 countries, 6 regions,
 * 31 goods) driven through src/integration/index.ts, as the game would use it.
 *
 *   npm run bench:integration
 *
 * Measures the bundle the game would load lazily, starting from the pre-built save, creating a session, resolving weeks through
 * advanceEconomyWeek (copy + week + summary), saving and restoring, in headless Chromium at
 * 1x, 4x and 6x CPU throttle. Chromium (V8) is NOT Safari: an order-of-magnitude proxy for a
 * phone, not a device measurement. Writes reports/INTEGRATION_BENCHMARK.md.
 */
const path = require('node:path');
const fs = require('node:fs');
const zlib = require('node:zlib');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const esbuild = path.resolve(root, '..', 'node_modules', '.bin', 'esbuild');
const tmp = process.env.TMPDIR || '/tmp';

function bundle(entry, name) {
  const out = path.join(tmp, `heartland-${name}-${process.pid}.js`);
  execFileSync(esbuild, [entry, '--bundle', '--minify', '--format=iife', '--global-name=EconomyIntegration', '--target=es2020', `--outfile=${out}`], { stdio: 'pipe' });
  const code = fs.readFileSync(out, 'utf8');
  fs.unlinkSync(out);
  return { code, kb: code.length / 1024, gzipKb: zlib.gzipSync(code).length / 1024 };
}

const integration = bundle(path.join(root, 'src', 'integration', 'index.ts'), 'integration');
const startingSave = fs.readFileSync(path.join(root, 'scenarios', 'fictional-week1.economy.json'), 'utf8');
const { chromium } = require('playwright');

(async () => {
  const browser = await chromium.launch();
  const results = [];
  for (const rate of [1, 4, 6]) {
    const page = await browser.newPage();
    const client = await page.context().newCDPSession(page);
    await page.setContent('<html><body></body></html>');
    const loadStart = Date.now();
    await page.addScriptTag({ content: integration.code });
    const scriptMs = Date.now() - loadStart;
    await client.send('Emulation.setCPUThrottlingRate', { rate });
    const result = await page.evaluate(saveText => {
      const E = window.EconomyIntegration;
      const median = values => values.slice().sort((a, b) => a - b)[values.length >> 1];
      const startTimes = [];
      let started = null;
      for (let k = 0; k < 5; k++) {
        const s = performance.now();
        started = E.startEconomyFromSave(saveText, E.fictionalGameWorld('alden'));
        startTimes.push(performance.now() - s);
      }
      const t0 = performance.now();
      let session = E.createEconomySession(E.fictionalGameWorld('alden'));
      const createMs = performance.now() - t0;
      const sameStart = E.economyFingerprint(started) === E.economyFingerprint(session);
      const times = [];
      const gameStart = performance.now();
      for (let week = 2; week <= 156; week++) {
        const s = performance.now();
        session = E.advanceEconomyWeek(session, week === 3 ? { playerCommands: [{ type: 'set-tax', countryId: 'alden', tax: 'income', rate: 0.2 }] } : {});
        times.push(performance.now() - s);
      }
      const gameMs = performance.now() - gameStart;
      const saveStart = performance.now();
      const text = E.saveEconomySession(session);
      const saveMs = performance.now() - saveStart;
      const loadStart = performance.now();
      const restored = E.loadEconomySession(text);
      const loadMs = performance.now() - loadStart;
      return { startMs: median(startTimes), sameStart, createMs, weekMedianMs: median(times), weekWorstMs: Math.max(...times), gameMs, saveMs, loadMs, saveKb: text.length / 1024,
        fingerprint: E.economyFingerprint(restored), week: session.week };
    }, startingSave);
    results.push({ rate, scriptMs, ...result });
    await page.close();
  }
  await browser.close();
  const lines = ['# Integration API benchmark (ECON-05)', '',
    'Generated by `npm run bench:integration`. The game\'s fictional scenario (Alden, Belora, Cyrin; six regions; 31 goods, 10 sectors) driven through `src/integration/index.ts`: the session is created, then weeks 2 to 156 are resolved with `advanceEconomyWeek` (a copy of the state, the week with the AI autopilot, and the weekly summary), then the session is saved and restored. Headless Chromium with CPU throttling: a rough stand-in for a phone (V8 is not Safari).', '',
    `Bundle the game would load lazily when a game starts (integration API + engine + catalogue, no dependencies): **${integration.kb.toFixed(0)} KB minified, ${integration.gzipKb.toFixed(0)} KB gzip**.`, '',
    `Pre-built starting save (\`scenarios/fictional-week1.economy.json\`): ${(startingSave.length / 1024).toFixed(0)} KB, ${(zlib.gzipSync(startingSave).length / 1024).toFixed(0)} KB gzip. Starting from it gives the same economy as building it: ${results.every(r => r.sameStart) ? 'yes, at every throttle level' : '**NO**'}.`, '',
    '| CPU throttle | start from save (ms) | create session (ms) | week, median (ms) | week, worst (ms) | 155 weeks in total (s) | save (ms) | load (ms) | save size (KB) |',
    '|---|---:|---:|---:|---:|---:|---:|---:|---:|',
    ...results.map(r => `| ${r.rate}x | ${r.startMs.toFixed(1)} | ${r.createMs.toFixed(0)} | ${r.weekMedianMs.toFixed(2)} | ${r.weekWorstMs.toFixed(1)} | ${(r.gameMs / 1000).toFixed(2)} | ${r.saveMs.toFixed(1)} | ${r.loadMs.toFixed(1)} | ${r.saveKb.toFixed(0)} |`), '',
    `Fingerprint after week ${results[0].week}: ${results[0].fingerprint}${results.every(r => r.fingerprint === results[0].fingerprint) ? ' (identical at every throttle level)' : ' (**differs between runs**)'}.`, ''];
  const text = lines.join('\n');
  fs.mkdirSync(path.join(root, 'reports'), { recursive: true });
  fs.writeFileSync(path.join(root, 'reports', 'INTEGRATION_BENCHMARK.md'), text);
  fs.writeFileSync(path.join(root, 'reports', 'integration-benchmark.json'), JSON.stringify({ bundleKb: integration.kb, gzipKb: integration.gzipKb, startingSaveKb: startingSave.length / 1024, results }, null, 2));
  console.log(text);
})().catch(error => { console.error(error); process.exit(1); });
